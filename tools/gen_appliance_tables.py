#!/usr/bin/env python3
"""Generate the C++ tables for the Smart Appliance slices from schema/*.json.

Inputs (all JSON, standard library only):
    schema/types.json           canonical scalars, persistence, access, shared enums
    schema/clusters/*.json      one file per cluster, read in CLUSTER_ORDER
    schema/appliances/*.json    one file per appliance
    schema/bindings/mqtt.json   MQTT tokens for the above

Outputs (checked in; scenarios/schema_generated.py fails if they drift):
    Enums.h                C++ enums and their logical names, MaintenanceCommand, EventKind
    MqttTables.h           MQTT topic, verb, event and positive-control tables
    Rulebooks.h            Cluster:MAST rulebook tables from schema/rulebooks/*.json
    <Name>Appliance.h      per appliance: role, attribute metadata, the faults it may raise,
                           and a <Name>Schema traits struct bundling them for the cores

Usage:
    python3 tools/gen_appliance_tables.py [--out DIR]   (default: src/codeline/generated)
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCHEMA = os.path.join(ROOT, "schema")  # --schema overrides it
DEFAULT_OUT = os.path.join(ROOT, "src", "codeline", "generated")
GATES = {"anytime": "Anytime", "by_access": "ByAccess", "offline": "Offline"}
BANNER = "// GENERATED by tools/gen_appliance_tables.py from schema/. Do not edit.\n"

# Clusters in the order their enums and events are emitted. Appending keeps
# every existing enum value and EventKind index stable.
CLUSTER_ORDER = ["maintenance", "turnout", "sensor", "holdoff", "mast", "lever", "button"]


class SchemaError(Exception):
    pass


def require(condition, message):
    if not condition:
        raise SchemaError(message)


def load(*parts):
    path = os.path.join(SCHEMA, *parts)
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def camel(name):
    """IN_TRANSIT -> InTransit, exportConfig -> ExportConfig, turnout.sim_transit_ms -> TurnoutSimTransitMs,
    SP-1990 -> Sp1990."""
    words = name.replace(".", "_").replace("-", "_").split("_")
    return "".join(w[:1].upper() + (w[1:].lower() if w.isupper() else w[1:]) for w in words if w)


def quoted(s):
    return '"' + s + '"' if s is not None else "nullptr"


# --------------------------------------------------------------------------- load & check


def load_model():
    types = load("types.json")
    on_disk = sorted(f[:-len(".json")] for f in os.listdir(os.path.join(SCHEMA, "clusters")) if f.endswith(".json"))
    require(on_disk == sorted(CLUSTER_ORDER), f"schema/clusters/ holds {on_disk}; CLUSTER_ORDER lists {CLUSTER_ORDER}")
    clusters = [load("clusters", f"{name}.json") for name in CLUSTER_ORDER]
    appliances = [load("appliances", f) for f in sorted(os.listdir(os.path.join(SCHEMA, "appliances"))) if f.endswith(".json")]
    mqtt = load("bindings", "mqtt.json")
    rulebook_dir = os.path.join(SCHEMA, "rulebooks")
    rulebooks = [load("rulebooks", f) for f in sorted(os.listdir(rulebook_dir)) if f.endswith(".json")]

    enums = {}
    for name, e in types["enums"].items():
        enums[name] = e["values"]
    composites = types.get("composites", {})
    for c in clusters:
        for name, e in c.get("enums", {}).items():
            require(name not in enums, f"enum {name} declared twice")
            enums[name] = e["values"]
    for name, values in enums.items():
        require(len(values) == len(set(values)), f"enum {name} has duplicate values")

    faults = types["enums"]["FaultType"]
    require(set(faults["declared_by"]) == set(faults["values"]), "FaultType.declared_by must cover every value")

    by_name = {c["cluster"]: c for c in clusters}
    for c in clusters:
        for ev in c.get("events", []):
            for ft in ev.get("fault_types", []):
                require(faults["declared_by"].get(ft) == c["cluster"],
                        f"{c['cluster']} lists fault {ft} declared by another cluster")

    composed = [load_appliance(a, by_name, types, enums, faults, composites) for a in appliances]
    require(len({a["appliance"]["role"] for a in composed}) == len(composed), "appliance roles must be unique")

    maint_wire = mqtt["clusters"]["MAINTENANCE"]
    maint = by_name["MAINTENANCE"]
    for c in maint["commands"]:
        require(c.get("gate") in GATES, f"MAINTENANCE.{c['name']}: gate must be one of {sorted(GATES)}")
    for name in mqtt["broadcast"]["commands"]:
        require(name in maint_wire["commands"], f"broadcast command {name} is not a MAINTENANCE command")
    require(mqtt["will"]["topic"] in mqtt["topics"], "will topic must be one of the topics")
    rc = mqtt["reconnect"]
    require(all(isinstance(rc[k], int) and rc[k] > 0 for k in ("initial_ms", "factor", "max_ms")) and
            0 <= rc["skew_permille"] <= 1000 and rc["initial_ms"] <= rc["max_ms"] and
            rc["max_ms"] * (1000 + rc["skew_permille"]) // 1000 < 2**31,
            "mqtt.json reconnect: positive initial_ms <= max_ms, factor >= 1, skew_permille 0..1000")
    require([c["name"] for c in maint["commands"]] == list(maint_wire["commands"]),
            "mqtt.json MAINTENANCE commands must list every command in schema order")
    require([e["name"] for e in maint["events"]] == list(maint_wire["events"]),
            "mqtt.json MAINTENANCE events must list every event in schema order")
    for e in maint["events"]:
        require((maint_wire["events"][e["name"]] is None) == bool(e.get("transport_only")),
                f"{e['name']}: only transport-only events have no MQTT token")

    # EventKind: MAINTENANCE's events, then every domain event that is not a
    # FaultEvent (domain FaultEvents only add FaultTypes), in cluster order.
    events = [(e["name"], maint_wire["events"][e["name"]]) for e in maint["events"]]
    owners = ["MAINTENANCE"] * len(events)
    for c in clusters:
        if c["cluster"] == "MAINTENANCE":
            continue
        for e in c.get("events", []):
            if e["name"] == "FaultEvent":
                require("payload" not in e, f"{c['cluster']}.FaultEvent: use fault_types, not a payload")
                continue
            require(e["name"] not in [n for n, _ in events], f"event {e['name']} declared twice")
            noun = mqtt["clusters"].get(c["cluster"], {}).get("events", {}).get(e["name"])
            require(noun is not None, f"mqtt.json has no token for {c['cluster']}.{e['name']}")
            events.append((e["name"], noun))
            owners.append(c["cluster"])

    turnout_wire = mqtt["clusters"]["TURNOUT"]
    for enum_name in ("TurnoutCommand", "TurnoutState"):
        table = turnout_wire[enum_name]
        require(list(table) == enums[enum_name], f"mqtt.json {enum_name} must list every value in order")
        pairs = [tuple(v) for v in table.values()]
        require(len(pairs) == len(set(pairs)), f"mqtt.json {enum_name} pairs must be distinct")
        require((True, True) not in pairs, f"mqtt.json {enum_name}: both asserted must stay invalid")
    require(list(mqtt["enums"]["SetOp"]) == enums["SetOp"], "mqtt.json SetOp must list every value in order")
    for cluster, keys in (("SENSOR", ["active"]), ("MAST", ["lit"]), ("LEVER", ["switch", "lamp"])):
        for k in keys:
            require(isinstance(mqtt["clusters"][cluster].get(k), str), f"mqtt.json {cluster}.{k} token missing")

    # One rulebook file per Rulebook enum value, in enum order.
    require([r["rulebook"] for r in rulebooks] == sorted(enums["Rulebook"]) and
            sorted(enums["Rulebook"]) == enums["Rulebook"],
            "schema/rulebooks/ must hold exactly one file per Rulebook value, Rulebook listed in sorted order")
    heads = next(a for a in by_name["MAST"]["attributes"] if a["name"] == "heads")
    min_heads, max_heads = heads["min"], heads["max"]
    for r in rulebooks:
        seen = set()
        for row in r["rows"]:
            require(row["indication"] in enums["SignalIndication"], f"{r['rulebook']}: unknown indication {row['indication']}")
            require(1 <= len(row["heads"]) <= max_heads, f"{r['rulebook']}: {row['indication']} has a bad head count")
            key = (len(row["heads"]), row["indication"])
            require(key not in seen, f"{r['rulebook']}: {row['indication']} on {len(row['heads'])} heads given twice")
            seen.add(key)
            for h in row["heads"]:
                require(parse_head(h)[0] in enums["ColorName"], f"{r['rulebook']}: bad head aspect {h}")
        # Every head count mast.heads allows must be able to show STOP, so a
        # mast can never be configured into a state it cannot stop.
        for n in range(min_heads, max_heads + 1):
            require((n, "STOP") in seen,
                    f"{r['rulebook']}: no STOP row for {n} heads, which mast.heads allows (lower mast.heads max)")

    return {
        "enums": enums,
        "maintenance": maint,
        "events": events,
        "event_owners": owners,
        "bitvector_width": composites["BitVector"]["width"],
        "appliances": composed,
        "mqtt": mqtt,
        "rulebooks": rulebooks,
        "max_heads": max_heads,
    }


def parse_head(text):
    """"RED" -> ("RED", False); "flashing YELLOW" -> ("YELLOW", True)."""
    words = text.split()
    if len(words) == 2 and words[0] == "flashing":
        return words[1], True
    require(len(words) == 1, f"bad head aspect {text!r}")
    return words[0], False


def load_appliance(appliance, by_name, types, enums, faults, composites):
    for req in appliance["clusters"]["required"]:
        require(req in by_name, f"Appliance:{appliance['appliance']} needs Cluster:{req}, which has no schema")
    require(appliance["clusters"]["required"][0] == "MAINTENANCE",
            f"Appliance:{appliance['appliance']} must compose MAINTENANCE first")

    # Faults the appliance may raise: MAINTENANCE's universal ones, those its
    # composed clusters declare, and any the appliance adds itself.
    composed = set(appliance["clusters"]["required"])
    raised = {ft for ft, owner in faults["declared_by"].items() if owner in composed}
    for extra in appliance.get("additional_faults", {}):
        require(extra in faults["values"], f"additional fault {extra} is not a FaultType")
        require(extra not in raised, f"additional fault {extra} is already declared by a composed cluster")
        raised.add(extra)

    # Attributes in composition order: MAINTENANCE first, then each composed cluster.
    attributes = []
    for name in appliance["clusters"]["required"]:
        c = by_name[name]
        for a in c.get("attributes", []):
            attributes.append(check_attribute(c["prefix"], a, types, enums, composites))
    # AttrMap::kCapacity (one map carries every attribute) is checked by a
    # static_assert in the generated header, against the C++ constant itself.
    paths = [a["path"] for a in attributes]
    for path, value in appliance.get("defaults", {}).items():
        require(path in paths, f"appliance default for unknown attribute {path}")
        attr = next(a for a in attributes if a["path"] == path)
        attr["default"] = value
        attr["raw_default"] = raw_value(attr, value, enums)

    return {
        "appliance": appliance,
        "attributes": attributes,
        "faults": [ft in raised for ft in faults["values"]],
        "composed": composed,
    }


def check_attribute(prefix, a, types, enums, composites):
    path = f"{prefix}.{a['name']}"
    t = a["type"]
    require(t in types["scalars"] or t in enums, f"{path}: unknown type {t}")
    require(a["persistence"] in types["persistence"], f"{path}: bad persistence {a['persistence']}")
    require(a["access"] in types["access"], f"{path}: bad access {a['access']}")
    attr = dict(a, path=path)
    attr["scale"] = 1
    if t in enums:
        attr["kind"], attr["max"] = "Enum", len(enums[t]) - 1
    elif t == "bool":
        attr["kind"], attr["max"] = "Bool", 1
    else:
        scalar = types["scalars"][t]
        attr["scale"] = scalar.get("scale", 1)
        require(attr["scale"] in (1, 100), f"{path}: only scale 1 and 100 are supported")
        attr["kind"] = "Uint" if attr["scale"] == 1 else "Hundredths"
        attr["max"] = scalar["max"]
    # Schema bounds narrow the type's range; they are written in logical units.
    attr["min"] = 0
    if "min" in a:
        require(attr["kind"] in ("Uint", "Hundredths"), f"{path}: min/max only on numbers")
        attr["min"] = scaled(path, a["min"], attr["scale"])
    if "max" in a:
        require(attr["kind"] in ("Uint", "Hundredths"), f"{path}: min/max only on numbers")
        attr["max"] = min(attr["max"], scaled(path, a["max"], attr["scale"]))
    # A channel count of a composite (BitVector) is bounded by its width.
    if "channels" in a:
        require(attr["kind"] == "Uint", f"{path}: a channel count must be an unsigned integer")
        width = composites[a["channels"]]["width"]
        require("max" not in a or a["max"] <= width,
                f"{path}: max {a.get('max')} exceeds the {a['channels']} width {width}")
        attr["max"] = min(attr["max"], width)
    require(attr["min"] <= attr["max"], f"{path}: min above max")
    attr["raw_default"] = raw_value(attr, a["default"], enums)
    return attr


def scaled(path, value, scale):
    require(isinstance(value, (int, float)) and not isinstance(value, bool), f"{path}: bound must be a number")
    raw = round(value * scale)
    require(abs(raw - value * scale) < 1e-6, f"{path}: {value} has more precision than 1/{scale}")
    return raw


def raw_value(attr, value, enums):
    if attr["kind"] == "Enum":
        require(value in enums[attr["type"]], f"{attr['path']}: default {value} is not a {attr['type']}")
        return enums[attr["type"]].index(value)
    if attr["kind"] == "Bool":
        require(isinstance(value, bool), f"{attr['path']}: default must be a bool")
        return int(value)
    raw = scaled(attr["path"], value, attr["scale"])
    require(attr["min"] <= raw <= attr["max"], f"{attr['path']}: default out of range")
    return raw


