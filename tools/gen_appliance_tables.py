def emit_enums(m):
    out = [BANNER, "#pragma once\n\n#include <cstdint>\n\n#include \"codeline/core/Attributes.h\"\n#include \"codeline/core/Text.h\"\n\n",
           "namespace codeline {\n"]
    for name, values in m["enums"].items():
        members = ", ".join(camel(v) for v in values)
        names = ", ".join(quoted(v) for v in values)
        out.append(f"\nenum class {name} : uint8_t {{ {members} }};\n")
        out.append(f"inline constexpr uint8_t k{name}Count = {len(values)};\n")
        out.append(f"inline constexpr const char* k{name}Names[] = {{{names}}};\n")
        out.append(f"template <>\nstruct EnumText<{name}> {{\n"
                   f"  static constexpr const char* const* names = k{name}Names;\n"
                   f"  static constexpr uint8_t count = k{name}Count;\n}};\n")

    out.append(f"\n// schema/types.json composites.BitVector.width: the most channels one BitVector carries.\n"
               f"inline constexpr uint8_t kBitVectorWidth = {m['bitvector_width']};\n")
    out.append("// schema/types.json scale 100 is AttrType::Hundredths.\n"
               "static_assert(kHundredthsPerUnit == 100, \"the generator maps scale 100 to AttrType::Hundredths\");\n")
    out.append("\n// Cluster:MAINTENANCE attribute paths, the same on every appliance.\n")
    for a in m["maintenance"]["attributes"]:
        out.append(f"inline constexpr const char* k{camel('maintenance.' + a['name'])}Path = {quoted('maintenance.' + a['name'])};\n")

    commands = [camel(c["name"]) for c in m["maintenance"]["commands"]]
    out.append("\n// Cluster:MAINTENANCE commands, in schema order.\n")
    out.append(f"enum class MaintenanceCommand : uint8_t {{ {', '.join(commands)} }};\n")
    out.append(f"inline constexpr uint8_t kMaintenanceCommandCount = {len(commands)};\n")
    gates = ", ".join("CommandGate::" + GATES[c["gate"]] for c in m["maintenance"]["commands"])
    out.append(f"inline constexpr CommandGate kMaintenanceCommandGates[] = {{{gates}}};\n")

    events = [camel(name[:-len("Event")]) for name, _ in m["events"]]
    out.append("\n// Events (ApplianceEvent::kind): Cluster:MAINTENANCE's, then each domain cluster's, in schema order.\n")
    out.append(f"enum class EventKind : uint8_t {{ {', '.join(events)} }};\n")
    out.append(f"inline constexpr uint8_t kEventKindCount = {len(events)};\n")
    out.append(f"inline constexpr const char* kEventKindNames[] = {{{', '.join(quoted(e) for e in events)}}};\n")
    out.append("\n}  // namespace codeline\n")
    return "".join(out)


def emit_mqtt(m):
    mq = m["mqtt"]
    maint = mq["clusters"]["MAINTENANCE"]
    turnout = mq["clusters"]["TURNOUT"]
    out = [BANNER, "#pragma once\n\n#include <cstdint>\n\n#include \"codeline/generated/Enums.h\"\n\n",
           "namespace codeline::mqtt {\n\n// Topic suffixes: {appliance}/<suffix>, except kTopicAll which is {channel}/all.\n"]
    for topic, spec in mq["topics"].items():
        out.append(f"inline constexpr const char* kTopic{camel(topic)} = {quoted(topic)};\n")
        out.append(f"inline constexpr bool kTopic{camel(topic)}Retained = {str(spec['retained']).lower()};\n")
    will = mq["will"]
    out.append(f"\n// Last will, registered by every appliance client: {{appliance}}/<kWillTopic>.\n")
    out.append(f"inline constexpr const char* kWillTopic = {quoted(will['topic'])};\n")
    out.append(f"inline constexpr const char* kWillPayload = {quoted(will['payload'])};\n")
    out.append(f"inline constexpr bool kWillRetained = {str(will['retained']).lower()};\n")
    rc = mq["reconnect"]
    out.append("\n// Reconnect backoff after a link loss (mqtt.json reconnect; see ReconnectBackoff.h).\n")
    out.append(f"inline constexpr uint32_t kReconnectInitialMs = {rc['initial_ms']};\n")
    out.append(f"inline constexpr uint32_t kReconnectFactor = {rc['factor']};\n")
    out.append(f"inline constexpr uint32_t kReconnectMaxMs = {rc['max_ms']};\n")
    out.append(f"inline constexpr uint32_t kReconnectSkewPermille = {rc['skew_permille']};\n")
    bc = mq["broadcast"]
    out.append(f"\n// {{channel}}/all: \"[<kGroupPrefix> <slug>] <COMMAND>\", answered after 0..jitter ms.\n")
    out.append(f"inline constexpr const char* kGroupPrefix = {quoted(bc['group_prefix'])};\n")
    out.append(f"inline constexpr uint32_t kBroadcastJitterMaxMs = {bc['jitter_max_ms']};\n")
    out.append(f"\ninline constexpr const char* kBoolTrue = {quoted(mq['bool']['true'])};\n")
    out.append(f"inline constexpr const char* kBoolFalse = {quoted(mq['bool']['false'])};\n")

    ops = ", ".join(quoted(v) for v in mq["enums"]["SetOp"].values())
    out.append(f"\n// Indexed by SetOp.\ninline constexpr const char* kSetOpTokens[] = {{{ops}}};\n")

    verbs = ", ".join(quoted(v) for v in maint["commands"].values())
    out.append(f"\n// /maint verbs, indexed by MaintenanceCommand.\n"
               f"inline constexpr const char* kMaintenanceVerbs[] = {{{verbs}}};\n")
    cmd_names = [c["name"] for c in m["maintenance"]["commands"]]
    flags = ", ".join("true" if n in mq["broadcast"]["commands"] else "false" for n in cmd_names)
    out.append(f"// Which MaintenanceCommands {{channel}}/all may carry, indexed by MaintenanceCommand.\n"
               f"inline constexpr bool kMaintenanceBroadcast[] = {{{flags}}};\n")

    nouns = ", ".join(quoted(noun) for _, noun in m["events"])
    out.append(f"\n// /event nouns, indexed by EventKind; nullptr = never on the wire.\n"
               f"inline constexpr const char* kEventNouns[] = {{{nouns}}};\n")

    clusters = mq["clusters"]
    out.append("\n// Cluster:SENSOR /state: ACTIVE | (ACTIVE).\n")
    out.append(f"inline constexpr const char* kSensorActiveToken = {quoted(clusters['SENSOR']['active'])};\n")
    out.append("// Cluster:MAST: <INDICATION> (SignalIndication names) with LIT | (LIT).\n")
    out.append(f"inline constexpr const char* kMastLitToken = {quoted(clusters['MAST']['lit'])};\n")
    out.append("// Cluster:LEVER: SW1 (SW2) ... on /state, LAMP1 (LAMP2) ... on /cmd.\n")
    out.append(f"inline constexpr const char* kLeverSwitchToken = {quoted(clusters['LEVER']['switch'])};\n")
    out.append(f"inline constexpr const char* kLeverLampToken = {quoted(clusters['LEVER']['lamp'])};\n")
    out.append("// Cluster:BUTTON /event: BTN<k> | (BTN<k>).\n")
    out.append(f"inline constexpr const char* kButtonToken = {quoted(clusters['BUTTON']['events']['ButtonEvent'])};\n")

    first, second = turnout["pair"]
    out.append("\n// Cluster:TURNOUT positive-control pair: \"NORMAL (REVERSE)\" etc.\n"
               "struct PairBits {\n  bool first;\n  bool second;\n};\n")
    out.append(f"inline constexpr const char* kTurnoutPairFirst = {quoted(first)};\n")
    out.append(f"inline constexpr const char* kTurnoutPairSecond = {quoted(second)};\n")
    for enum_name in ("TurnoutCommand", "TurnoutState"):
        table = turnout[enum_name]
        bits = ", ".join("{%s, %s}" % (str(a).lower(), str(b).lower()) for a, b in table.values())
        frames = ", ".join(quoted(frame(first, a) + " " + frame(second, b)) for a, b in table.values())
        out.append(f"\n// Indexed by {enum_name}.\n")
        out.append(f"inline constexpr PairBits k{enum_name}Pairs[] = {{{bits}}};\n")
        out.append(f"inline constexpr const char* k{enum_name}Frames[] = {{{frames}}};\n")
    out.append("\n}  // namespace codeline::mqtt\n")
    return "".join(out)


def frame(token, asserted):
    return token if asserted else f"({token})"


def emit_attributes(m, model):
    app = m["appliance"]
    clusters = ", ".join(app["clusters"]["required"])
    name = camel(app["appliance"])
    attrs = m["attributes"]
    persistence = {"volatile": "Volatile", "nv_config": "NvConfig", "nv_state": "NvState"}
    access = {"RO": "RO", "RW": "RW", "VITAL": "Vital"}
    out = [BANNER, "#pragma once\n\n#include <cstdint>\n\n#include \"codeline/core/Attributes.h\"\n"
           "#include \"codeline/generated/Enums.h\"\n\n", "namespace codeline {\n\n"]
    out.append(f"inline constexpr const char* k{name}Role = {quoted(app['role'])};\n\n")
    out.append(f"// Appliance:{app['appliance']} attributes ({clusters}), indexed into k{name}Attributes.\n")
    members = ", ".join(camel(a["path"]) for a in attrs)
    out.append(f"enum class {name}Attr : uint8_t {{ {members} }};\n")
    out.append(f"inline constexpr uint8_t k{name}AttrCount = {len(attrs)};\n")
    out.append(f"static_assert(k{name}AttrCount <= AttrMap::kCapacity, \"one AttrMap must carry every attribute\");\n\n")
    out.append(f"inline constexpr AttributeInfo k{name}Attributes[] = {{\n")
    for a in attrs:
        names = f"k{a['type']}Names" if a["kind"] == "Enum" else "nullptr"
        default = a["default"]
        comment = default if not isinstance(default, bool) else str(default).lower()
        out.append(f"    {{{quoted(a['path'])}, AttrType::{a['kind']}, Persistence::{persistence[a['persistence']]}, "
                   f"Access::{access[a['access']]}, {str(bool(a.get('clearable'))).lower()}, "
                   f"{a['raw_default']}u /* {comment} */, {a['min']}u, {a['max']}u, {names}}},\n")
    out.append("};\n\n")
    out.append(f"inline constexpr AttributeTable k{name}AttributeTable{{k{name}Attributes, k{name}AttrCount}};\n")
    flags = ", ".join(str(f).lower() for f in m["faults"])
    out.append(f"\n// Which FaultTypes Appliance:{app['appliance']} may raise, indexed by FaultType.\n")
    out.append(f"inline constexpr bool k{name}Faults[] = {{{flags}}};\n")
    out.append(f"constexpr bool {app['role']}Raises(FaultType t) {{ return k{name}Faults[static_cast<uint8_t>(t)]; }}\n")
    emits = ", ".join(str(owner in m["composed"]).lower() for owner in model["event_owners"])
    out.append(f"\n// Which events Appliance:{app['appliance']} emits, indexed by EventKind.\n")
    out.append(f"inline constexpr bool k{name}Events[] = {{{emits}}};\n")
    out.append(f"\n// Everything a core needs about Appliance:{app['appliance']}, in one place.\n")
    out.append(f"struct {name}Schema {{\n"
               f"  using Attr = {name}Attr;\n"
               f"  static constexpr const char* role = k{name}Role;\n"
               f"  static constexpr const AttributeInfo* attributes = k{name}Attributes;\n"
               f"  static constexpr uint8_t attr_count = k{name}AttrCount;\n"
               f"  static constexpr const AttributeTable& table = k{name}AttributeTable;\n"
               f"  static constexpr bool raises(FaultType t) {{ return {app['role']}Raises(t); }}\n"
               f"  static constexpr const bool* events = k{name}Events;\n"
               f"}};\n")
    out.append("\n}  // namespace codeline\n")
    return "".join(out)


def emit_rulebooks(m):
    out = [BANNER, "#pragma once\n\n#include <cstdint>\n\n#include \"codeline/generated/Enums.h\"\n\n",
           "namespace codeline {\n\n"]
    n = m["max_heads"]
    out.append(f"inline constexpr uint8_t kMaxHeads = {n};  // mast.heads maximum\n\n")
    out.append("struct HeadAspect {\n  ColorName color;\n  bool flashing;\n};\n\n")
    out.append("// One (heads, indication) entry: aspect[i] is head i (0 = head.A).\n"
               f"struct RulebookRow {{\n  uint8_t heads;\n  SignalIndication indication;\n  HeadAspect aspect[kMaxHeads];\n}};\n\n")
    out.append("struct RulebookTable {\n  const RulebookRow* rows;\n  uint8_t count;\n};\n")
    tables = []
    for r in m["rulebooks"]:
        ident = camel(r["rulebook"])
        out.append(f"\n// {r['rulebook']}: schema/rulebooks/{r['rulebook']}.json\n")
        out.append(f"inline constexpr RulebookRow k{ident}Rows[] = {{\n")
        for row in r["rows"]:
            heads = [parse_head(h) for h in row["heads"]]
            heads += [("NONE", False)] * (n - len(heads))
            cells = ", ".join(f"{{ColorName::{camel(c)}, {str(f).lower()}}}" for c, f in heads)
            out.append(f"    {{{len(row['heads'])}, SignalIndication::{camel(row['indication'])}, {{{cells}}}}},\n")
        out.append("};\n")
        tables.append(f"{{k{ident}Rows, {len(r['rows'])}}}")
    out.append(f"\n// Indexed by Rulebook.\ninline constexpr RulebookTable kRulebooks[] = {{{', '.join(tables)}}};\n")
    out.append("\n}  // namespace codeline\n")
    return "".join(out)


def generate():
    m = load_model()
    files = {
        "Enums.h": emit_enums(m),
        "MqttTables.h": emit_mqtt(m),
        "Rulebooks.h": emit_rulebooks(m),
    }
    for a in m["appliances"]:
        files[f"{camel(a['appliance']['appliance'])}Appliance.h"] = emit_attributes(a, m)
    return files


def main():
    global SCHEMA
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=DEFAULT_OUT, help="output directory")
    parser.add_argument("--schema", default=SCHEMA, help="schema directory (default: schema/)")
    args = parser.parse_args()
    SCHEMA = args.schema
    try:
        files = generate()
    except (SchemaError, KeyError) as e:
        print(f"schema error: {e}", file=sys.stderr)
        return 1
    os.makedirs(args.out, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(args.out, name), "w", encoding="utf-8") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
